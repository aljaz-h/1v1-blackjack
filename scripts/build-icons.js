'use strict';
// Builds public/icons.js from Iconify icon sets (https://icon-sets.iconify.design/).
// Only the icons listed below are bundled, so there is no runtime request to the Iconify API
// (our CSP only allows same-origin). Re-run after editing the lists:  node scripts/build-icons.js
const { execFileSync } = require('node:child_process');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');

const SETS = {
  lucide: { pkg: '@iconify-json/lucide', prefix: '', icons: ['volume-2', 'volume-x', 'message-circle', 'chevrons-right', 'trophy', 'handshake', 'user-plus', 'armchair', 'log-out', 'swords', 'shuffle', 'timer', 'flag', 'wifi-off', 'plus', 'hand', 'chevrons-up', 'split', 'coins', 'arrow-right', 'check', 'x', 'users', 'eye', 'history', 'keyboard', 'copy', 'trending-up', 'trending-down', 'equal', 'crown', 'spade', 'send', 'triangle-alert', 'info', 'wifi', 'layers', 'clock', 'user-minus', 'play', 'pause', 'skull', 'dices', 'flame', 'ghost', 'rocket', 'zap', 'gem', 'cat', 'dog', 'bot', 'clover', 'star', 'bird', 'fish', 'palette', 'pencil'] },
  'line-md': { pkg: '@iconify-json/line-md', prefix: 'lm-', icons: ['confirm-circle', 'alert-circle-loop', 'loading-loop', 'check-all', 'close-circle', 'bell-loop'] }, // animated
  'svg-spinners': { pkg: '@iconify-json/svg-spinners', prefix: 'sp-', icons: ['180-ring-with-bg', '3-dots-bounce', '3-dots-fade', 'bars-scale-middle', 'pulse-3', 'clock'] }, // animated
};

const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'icons-'));
execFileSync('npm', ['pack', '--silent', ...Object.values(SETS).map((s) => s.pkg)], { cwd: tmp, stdio: ['ignore', 'ignore', 'inherit'] });
const out = {};
const credits = [];
for (const [name, set] of Object.entries(SETS)) {
  const tgz = fs.readdirSync(tmp).find((f) => f.startsWith(set.pkg.replace('@', '').replace('/', '-') + '-') && f.endsWith('.tgz'));
  const dir = path.join(tmp, name);
  fs.mkdirSync(dir);
  execFileSync('tar', ['-xzf', path.join(tmp, tgz), '-C', dir]);
  const data = JSON.parse(fs.readFileSync(path.join(dir, 'package', 'icons.json'), 'utf8'));
  const info = JSON.parse(fs.readFileSync(path.join(dir, 'package', 'info.json'), 'utf8'));
  for (const icon of set.icons) {
    let i = data.icons[icon];
    if (!i && data.aliases && data.aliases[icon]) i = data.icons[data.aliases[icon].parent];
    if (!i) throw new Error(`${name}:${icon} not found`);
    out[set.prefix + icon] = [i.width || data.width || 24, i.height || data.height || 24, i.body];
  }
  credits.push(`${info.name || name} by ${info.author && info.author.name} — ${info.license && info.license.title} — ${info.license && info.license.url}`);
}
const js = `/* generated by scripts/build-icons.js from Iconify icon sets; do not edit by hand */
(function () {
  var I = ${JSON.stringify(out)};
  window.ic = function (n, c) {
    var i = I[n];
    if (!i) return '';
    return '<svg class="ic' + (c ? ' ' + c : '') + '" viewBox="0 0 ' + i[0] + ' ' + i[1] + '" width="1em" height="1em" aria-hidden="true" focusable="false">' + i[2] + '</svg>';
  };
  window.hydrateIcons = function (root) {
    (root || document).querySelectorAll('[data-ic]').forEach(function (e) { e.innerHTML = window.ic(e.dataset.ic); e.removeAttribute('data-ic'); });
  };
})();
`;
fs.writeFileSync(path.join(__dirname, '..', 'public', 'icons.js'), js);
fs.writeFileSync(path.join(__dirname, '..', 'public', 'ICON-LICENSES.txt'), 'Icons are bundled from Iconify icon sets (https://icon-sets.iconify.design/):\n\n' + credits.join('\n') + '\n');
console.log(`wrote public/icons.js (${(js.length / 1024).toFixed(1)} KB, ${Object.keys(out).length} icons)`);
